// למה קובץ חיצוני ולא סקריפט inline ב-index.html: ה-CSP שלנו ב-vercel.json הוא
// script-src 'self' בלי unsafe-inline, ולכן סקריפט inline היה נחסם בפרודקשן ועובד רק
// בפיתוח - תקלה שהייתה מתגלה רק אחרי העלייה. הסורק שלנו בודק בדיוק את זה אצל אחרים,
// אז אנחנו לא מרככים את ה-CSP בשבילו.
//
// בלי זה, מבקר שמגיע ל-/en רואה לרגע פריסה מימין-לשמאל עד שהקומפוננטה מתקנת - הבהוב
// שנראה כמו תקלה. עברית היא ברירת המחדל שבתגית עצמה, ולכן צריך לטפל רק ב-/en.
(function () {
  var p = location.pathname;
  if (p === "/en" || p.indexOf("/en/") === 0) {
    document.documentElement.lang = "en";
    document.documentElement.dir = "ltr";
  }
})();
